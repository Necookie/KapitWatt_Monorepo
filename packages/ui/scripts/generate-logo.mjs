// Copies the logo geometry from @kapitwatt/assets (the source of truth) into src/logo-paths.ts,
// so <Logo> renders the exact approved artwork with react-native-svg.
//   pnpm --filter @kapitwatt/ui generate:logo     (rerun after packages/assets/source/build.py)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const logo = join(here, '..', '..', 'assets', 'logo');
const variants = {
  mark: 'kapitwatt-mark.svg',
  lockup: 'kapitwatt-lockup.svg',
  wordmark: 'kapitwatt-wordmark.svg',
};

let out =
  '// GENERATED by scripts/generate-logo.mjs from packages/assets/logo. Do not edit.\n\nexport const logoPaths = {\n';
for (const [name, file] of Object.entries(variants)) {
  const svg = readFileSync(join(logo, file), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const paths = [...svg.matchAll(/<path[^>]*?\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!viewBox || paths.length === 0) throw new Error(`could not read ${file}`);
  out += `  ${name}: { viewBox: ${JSON.stringify(viewBox)}, paths: ${JSON.stringify(paths)} },\n`;
}
out += '} as const;\n\nexport type LogoVariant = keyof typeof logoPaths;\n';
writeFileSync(join(here, '..', 'src', 'logo-paths.ts'), out);
console.log(`wrote ${Object.keys(variants).length} logo variants`);
