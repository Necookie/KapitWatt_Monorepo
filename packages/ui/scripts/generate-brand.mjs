// Copies brand artwork from @kapitwatt/assets (the source of truth) into ui source files:
//   src/logo-paths.ts   logo geometry, drawn by <Logo> with react-native-svg paths
//   src/mascot-xml.ts   Alitaptap poses as SVG markup, drawn by <Mascot> with SvgXml
//   pnpm --filter @kapitwatt/ui generate:brand     (rerun after the assets change)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, '..', '..', 'assets');

const variants = {
  mark: 'kapitwatt-mark.svg',
  lockup: 'kapitwatt-lockup.svg',
  wordmark: 'kapitwatt-wordmark.svg',
};
let logo =
  '// GENERATED by scripts/generate-brand.mjs from packages/assets/logo. Do not edit.\n\nexport const logoPaths = {\n';
for (const [name, file] of Object.entries(variants)) {
  const svg = readFileSync(join(assets, 'logo', file), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const paths = [...svg.matchAll(/<path[^>]*?\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!viewBox || paths.length === 0) throw new Error(`could not read ${file}`);
  logo += `  ${name}: { viewBox: ${JSON.stringify(viewBox)}, paths: ${JSON.stringify(paths)} },\n`;
}
logo += '} as const;\n\nexport type LogoVariant = keyof typeof logoPaths;\n';
writeFileSync(join(here, '..', 'src', 'logo-paths.ts'), logo);

let mascot =
  '// GENERATED by scripts/generate-brand.mjs from packages/assets/mascot. Do not edit.\n\nexport const mascotXml = {\n';
const poses = readdirSync(join(assets, 'mascot')).filter((f) => /^alitaptap-[a-z]+\.svg$/.test(f));
for (const file of poses.sort()) {
  const pose = file.replace(/^alitaptap-|\.svg$/g, '');
  // Decorative: drop the file's own role/aria-label (SvgXml would pass them on as invalid props).
  const svg = readFileSync(join(assets, 'mascot', file), 'utf8')
    .trim()
    .replace(/\s(role|aria-label)="[^"]*"/g, '');
  mascot += `  ${pose}: ${JSON.stringify(svg)},\n`;
}
mascot += '} as const;\n\nexport type MascotPose = keyof typeof mascotXml;\n';
writeFileSync(join(here, '..', 'src', 'mascot-xml.ts'), mascot);

console.log(`wrote ${Object.keys(variants).length} logo variants and ${poses.length} mascot poses`);
